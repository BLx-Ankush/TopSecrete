"""
Type definitions and data models for Alice Browser Automation.

This module contains all enums, dataclasses, and type definitions used throughout
the browser automation system.
"""

from enum import Enum
from dataclasses import dataclass, field
from typing import Dict, Any, List, Optional, Tuple
from datetime import datetime, date


# ============================================================================
# Enums
# ============================================================================

class TaskType(Enum):
    """Types of browser automation tasks"""
    WEB_BOOKING = "web_booking"
    PROBLEM_SOLVING = "problem_solving"
    APP_ACCESS = "app_access"


class ActionType(Enum):
    """Types of browser actions"""
    NAVIGATE = "navigate"
    CLICK = "click"
    TYPE = "type"
    WAIT = "wait"
    EXTRACT = "extract"
    SCROLL = "scroll"
    SELECT = "select"
    UPLOAD = "upload"
    DOWNLOAD = "download"


class SessionState(Enum):
    """Browser session states"""
    CREATING = "creating"
    ACTIVE = "active"
    IDLE = "idle"
    CRASHED = "crashed"
    CLOSING = "closing"


# ============================================================================
# DOM and Element Data Models
# ============================================================================

@dataclass
class ElementSelectors:
    """
    Multiple selector strategies for robust element identification.
    
    Provides fallback options when primary selector fails.
    """
    css_selector: str
    xpath: str
    aria_label: Optional[str] = None
    test_id: Optional[str] = None
    text_content: Optional[str] = None


@dataclass
class InteractiveElement:
    """
    Represents an interactive DOM element.
    
    Contains all information needed to identify and interact with
    a web page element.
    """
    element_id: str
    tag_name: str
    role: str  # ARIA role
    label: str
    selectors: ElementSelectors
    attributes: Dict[str, str]
    position: Tuple[int, int]  # x, y coordinates
    is_visible: bool


@dataclass
class AccessibilityNode:
    """
    Single node in the accessibility tree.
    
    Represents the semantic structure used by screen readers.
    """
    role: str
    name: str
    description: Optional[str] = None
    children: List['AccessibilityNode'] = field(default_factory=list)
    selectors: Optional[ElementSelectors] = None


@dataclass
class AccessibilityTree:
    """
    Browser's accessibility tree structure.
    
    Provides semantic representation of page for accurate element identification.
    """
    root: AccessibilityNode
    interactive_nodes: List[AccessibilityNode] = field(default_factory=list)


@dataclass
class StructuredDOM:
    """
    Structured representation of DOM for LLM processing.
    
    Contains parsed DOM data optimized for Qwen model consumption.
    """
    url: str
    title: str
    interactive_elements: List[InteractiveElement]
    text_content: str
    metadata: Dict[str, Any]
    timestamp: datetime = field(default_factory=datetime.now)


# ============================================================================
# Browser Action and Task Data Models
# ============================================================================

@dataclass
class BrowserAction:
    """
    Single browser action to be executed.
    
    Generated by Qwen model based on task and current DOM state.
    """
    action_type: ActionType
    target_selector: Optional[ElementSelectors] = None
    parameters: Dict[str, Any] = field(default_factory=dict)
    expected_result: str = ""
    retry_count: int = 0


@dataclass
class BrowserTask:
    """
    High-level browser automation task.
    
    Represents user's intent translated from voice command.
    """
    task_id: str
    description: str
    task_type: TaskType
    parameters: Dict[str, Any]
    target_url: Optional[str] = None
    expected_outcome: str = ""


@dataclass
class BrowserState:
    """
    Current state of browser session.
    
    Captures all relevant state information for task execution.
    """
    url: str
    dom: Optional['StructuredDOM'] = None
    cookies: List[Dict[str, Any]] = field(default_factory=list)
    local_storage: Dict[str, str] = field(default_factory=dict)
    session_storage: Dict[str, str] = field(default_factory=dict)
    screenshot_path: Optional[str] = None


@dataclass
class TaskResult:
    """
    Result of browser automation task execution.
    
    Contains summary, extracted data, and execution details.
    """
    task_id: str
    success: bool
    summary: str
    actions_taken: List[BrowserAction] = field(default_factory=list)
    extracted_data: Dict[str, Any] = field(default_factory=dict)
    error: Optional[str] = None
    duration_seconds: float = 0.0
    screenshots: List[str] = field(default_factory=list)


# ============================================================================
# Session Data Models
# ============================================================================

@dataclass
class BrowserSession:
    """
    Active browser session with Playwright.
    
    Manages browser context and page lifecycle.
    """
    session_id: str
    profile_name: str
    domain: str
    playwright_context: Any  # BrowserContext from Playwright
    playwright_page: Any  # Page from Playwright
    created_at: datetime
    last_activity: datetime
    is_headless: bool
    state: SessionState


@dataclass
class RetryConfig:
    """
    Configuration for retry behavior.
    
    Defines retry limits and backoff strategy for error recovery.
    """
    max_retries: int = 2
    retry_delay_seconds: float = 1.0
    exponential_backoff: bool = True
    backoff_multiplier: float = 2.0
    
    # Error-specific retry limits
    element_not_found_retries: int = 3
    page_load_retries: int = 2
    invalid_action_retries: int = 3
    network_error_retries: int = 2


# ============================================================================
# Application Configuration Data Models
# ============================================================================

@dataclass
class AppConfig:
    """
    Configuration for web application access.
    
    Defines how to authenticate and navigate specific web applications.
    """
    app_name: str
    url: str
    login_url: str
    login_selectors: Dict[str, ElementSelectors]
    authenticated_indicator: ElementSelectors
    navigation_map: Dict[str, str]  # section -> URL path
    profile_name: str


# ============================================================================
# Action Suite Data Models
# ============================================================================

@dataclass
class TravelBookingDetails:
    """
    Parameters for travel booking tasks.
    
    Used by WebBookingsActionSuite for flight, hotel, and car bookings.
    """
    booking_type: str  # flight, hotel, car
    origin: Optional[str] = None
    destination: str = ""
    departure_date: Optional[date] = None
    return_date: Optional[date] = None
    passengers: int = 1
    class_preference: Optional[str] = None  # economy, business, first
    preferences: Dict[str, Any] = field(default_factory=dict)


@dataclass
class EventTicketDetails:
    """
    Parameters for event ticket booking.
    
    Used by WebBookingsActionSuite for event bookings.
    """
    event_name: str
    venue: Optional[str] = None
    date: Optional[date] = None
    time: Optional[str] = None
    ticket_count: int = 1
    seat_preference: Optional[str] = None
    ticket_type: Optional[str] = None  # VIP, general, etc.


@dataclass
class Solution:
    """
    Problem solution from web research.
    
    Used by ProblemSolvingActionSuite to represent potential solutions.
    """
    title: str
    source_url: str
    steps: List[str]
    commands: List[str] = field(default_factory=list)
    relevance_score: float = 0.0
    platform: str = "unknown"  # windows, linux, macos
    risk_level: str = "unknown"  # low, medium, high


@dataclass
class ExecutionResult:
    """
    Result of solution execution via Open Interpreter.
    
    Used by ProblemSolvingActionSuite to track command execution.
    """
    success: bool
    output: str
    error: Optional[str] = None
    verification_passed: bool = False


# ============================================================================
# Prompt and Model Data Models
# ============================================================================

@dataclass
class PromptContext:
    """
    Context for prompt generation.
    
    Contains all information needed to build effective prompts for Qwen model.
    """
    task_description: str
    current_dom: Optional[StructuredDOM] = None
    previous_actions: List[BrowserAction] = field(default_factory=list)
    error_context: Optional[str] = None
    few_shot_examples: List[Dict[str, str]] = field(default_factory=list)


@dataclass
class ModelResponse:
    """
    Response from Qwen model.
    
    Contains generated action and metadata about the generation.
    """
    action: Optional[BrowserAction] = None
    raw_response: str = ""
    is_valid: bool = False
    validation_error: Optional[str] = None
    generation_time_seconds: float = 0.0


# ============================================================================
# Progress and Callback Data Models
# ============================================================================

@dataclass
class ProgressUpdate:
    """
    Progress update for long-running tasks.
    
    Sent to Alice agent for user feedback.
    """
    task_id: str
    message: str
    progress_percent: float = 0.0
    current_action: Optional[str] = None
    timestamp: datetime = field(default_factory=datetime.now)


@dataclass
class UserConfirmation:
    """
    Request for user confirmation.
    
    Used for payment confirmations and security-sensitive operations.
    """
    confirmation_id: str
    message: str
    action_preview: str
    requires_voice_confirmation: bool = True
    timeout_seconds: int = 30
